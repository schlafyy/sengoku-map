"""Draws the Ryukyu islands for the insets south of Shikoku: the chain lies about 600 km south of the province map, where
its fitted projection (data/georef.js) no longer holds. As Japanese atlases do, the chain is cut in two: Okinawa and the
Amami islands in one box, the Sakishima islands (Miyako, Yaeyama) in a smaller one beside it, both at one plain lon/lat
projection close to the main map's scale. Coastlines from Natural Earth's 10m land (public domain). Writes data/ryukyu.js.
Run: python tools/ryukyu.py <path to ne_10m_land.geojson>"""
import json, math, os, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
K = 44  # map units per degree of latitude (the main map has about 50)
C = math.cos(math.radians(26.3))
# each box: what it shows (lon0, lon1, lat0, lat1) and where its top-left sits on the map. The Senkakus fall in neither:
# disputed, and never part of this story.
FRAMES = [
    {"name": "Ryukyu", "ja": "琉球", "lon0": 126.55, "lon1": 130.25, "lat0": 25.95, "lat1": 28.65, "x": 262, "y": 678},
    {"name": "Sakishima", "ja": "先島", "lon0": 122.8, "lon1": 125.55, "lat0": 23.95, "lat1": 25.05, "x": 146, "y": 748},
]


def frame_of(lons, lats):
    for i, f in enumerate(FRAMES):
        if f["lon0"] < min(lons) and max(lons) < f["lon1"] and f["lat0"] < min(lats) and max(lats) < f["lat1"]:
            return i
    return None


def main(src):
    for f in FRAMES:
        f["width"], f["height"] = round((f["lon1"] - f["lon0"]) * K * C, 1), round((f["lat1"] - f["lat0"]) * K, 1)
    a, b = FRAMES
    assert b["x"] + b["width"] < a["x"] and b["y"] + b["height"] <= a["y"] + a["height"], "the boxes overlap or misalign"
    shapes = []
    for feat in json.load(open(src, encoding="utf8"))["features"]:
        g = feat["geometry"]
        for poly in g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]:
            ring = poly[0]
            i = frame_of([c[0] for c in ring], [c[1] for c in ring])
            if i is None:
                continue
            f = FRAMES[i]
            d = "M" + "L".join(f"{f['x'] + (lon - f['lon0']) * K * C:.1f},{f['y'] + (f['lat1'] - lat) * K:.1f}" for lon, lat in ring) + "Z"
            shapes.append({"d": d, "m": [1, 0, 0, 1, 0, 0], "amami": min(c[1] for c in ring) > 27.5})
    out = {"source": "Natural Earth 10m land, public domain", "k": K, "c": C, "frames": FRAMES, "shapes": shapes}
    path = os.path.join(ROOT, "data", "ryukyu.js")
    open(path, "w", encoding="utf8").write("// Generated by tools/ryukyu.py: the Ryukyu islands, in two boxes south of Shikoku.\n"
                                           "const RYUKYU = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print("wrote", path, len(shapes), "islands,", sum(s["amami"] for s in shapes), "of them Amami;", [(f["name"], f["width"], f["height"]) for f in FRAMES])


if __name__ == "__main__":
    main(sys.argv[1])
