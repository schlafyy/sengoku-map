"""Warps Natural Earth's shaded relief (public domain, naturalearthdata.com, SR_HR 1:10m) onto the province map, using
the fit in data/georef.js, and writes images/relief.jpg plus its placement in data/relief.js.
Run: python tools/relief.py <path to SR_HR.tif>"""
import json, os, sys
import numpy as np
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
MAP_BOX = (0, 0, 760, 794)  # the province map's own coordinate space
SCALE = 2                   # output pixels per map unit


def main(tif):
    js = open(os.path.join(ROOT, "data", "georef.js"), encoding="utf8").read()
    inv = json.loads(js[js.index("{"):js.rindex("}") + 1])["toLonLat"]
    Image.MAX_IMAGE_PIXELS = None
    src = Image.open(tif)
    per_deg = src.width / 360  # an equirectangular world image: 21600 px = 360 degrees
    lon0, lon1, lat0, lat1 = 126.0, 148.0, 29.0, 47.0
    box = (int((lon0 + 180) * per_deg), int((90 - lat1) * per_deg), int((lon1 + 180) * per_deg), int((90 - lat0) * per_deg))
    crop = np.asarray(src.crop(box).convert("L"), dtype=np.float32)
    x0, y0, x1, y1 = MAP_BOX
    W, H = (x1 - x0) * SCALE, (y1 - y0) * SCALE
    xs, ys = np.meshgrid(np.linspace(x0, x1, W), np.linspace(y0, y1, H))
    t = np.stack([np.ones_like(xs), xs, ys, xs * ys, xs * xs, ys * ys])
    lon = np.tensordot(inv[0], t, axes=1); lat = np.tensordot(inv[1], t, axes=1)
    # bilinear sample of the crop at each output pixel's longitude and latitude
    u = np.clip((lon - lon0) * per_deg, 0, crop.shape[1] - 2); v = np.clip((lat1 - lat) * per_deg, 0, crop.shape[0] - 2)
    i, j = u.astype(int), v.astype(int); fu, fv = u - i, v - j
    out = (crop[j, i] * (1 - fu) * (1 - fv) + crop[j, i + 1] * fu * (1 - fv) + crop[j + 1, i] * (1 - fu) * fv + crop[j + 1, i + 1] * fu * fv)
    # stretch: the land's flat lowlands go to white, mountains keep their shading
    lo, hi = np.percentile(out, 2), np.percentile(out, 98)
    out = np.clip((out - lo) / (hi - lo) * 255, 0, 255).astype(np.uint8)
    path = os.path.join(ROOT, "images", "relief.jpg")
    Image.fromarray(out).save(path, "JPEG", quality=82, optimize=True)
    with open(os.path.join(ROOT, "data", "relief.js"), "w", encoding="utf8") as f:
        f.write("// Generated by tools/relief.py: Natural Earth shaded relief (public domain), warped onto the province map.\n")
        f.write("const RELIEF = " + json.dumps({"src": "images/relief.jpg", "x": x0, "y": y0, "width": x1 - x0, "height": y1 - y0}) + ";\n")
    print("wrote", path, f"{W}x{H}", os.path.getsize(path) // 1024, "KB")


if __name__ == "__main__":
    main(sys.argv[1])
