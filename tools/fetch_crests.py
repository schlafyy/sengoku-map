"""Downloads each clan's family crest (kamon) as SVG from its Wikipedia article (English, else Japanese), keeping only
public domain and Creative Commons files from Wikimedia Commons, into crests/ and data/crests.js.
Run: python tools/fetch_crests.py"""
import json, os, re, sys, time, urllib.parse, urllib.request

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import wiki_check as w  # load_history() reads history.js, places.js and modern.js
from fetch_images import file_info, OK_LICENCE

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "crests")
NO_CREST = {"east", "west", "tozama", "ikko", "saito", "imperial", "shogunate", "empire", "rebels"}  # coalitions and leagues; Saito: the article's crest is not Dosan's
# where the article's lead crest is wrong for the house, or drawn white on black (the resist filter needs dark on light)
CREST_FILE = {"rokkaku": "Japanese_crest_Yotumeyui.svg", "shimazu": "Maru_ni_Jū-monji_(Kutsuwa).svg", "toyotomi": "Goshichi_no_kiri.svg"}
EN_TITLES = {"hojo": "Later Hōjō clan", "wtakeda": "Wakasa Takeda clan", "ashikaga": "Ashikaga clan", "ouchi": "Ōuchi clan"}
JA_TITLES = {"hojo": "後北条氏", "wtakeda": "若狭武田氏", "takeda": "甲斐武田氏", "hosokawa": "細川氏", "toyotomi": "豊臣氏"}


def lead_image(api, title):
    url = api + "?" + urllib.parse.urlencode({"action": "query", "format": "json", "formatversion": 2, "prop": "pageimages",
                                              "piprop": "name", "redirects": 1, "titles": title})
    for attempt in range(5):
        time.sleep(5)
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=w.UA), timeout=30) as r:
                pages = json.load(r)["query"]["pages"]
            return pages[0].get("pageimage") if pages else None
        except Exception:
            time.sleep(15 * (attempt + 1))
    return None


def main():
    h = w.load_history()
    os.makedirs(OUT, exist_ok=True)
    path_js = os.path.join(ROOT, "data", "crests.js")
    result = {}
    if os.path.exists(path_js):  # resume: keep what an earlier run got
        text = open(path_js, encoding="utf8").read()
        result = {k: v for k, v in json.loads(text[text.index("{"):text.rindex("}") + 1]).items() if k not in CREST_FILE and k not in NO_CREST and v.get("artist")}
    skipped = []
    for k, c in h["CLANS"].items():
        if k in NO_CREST or k in result:
            continue
        found = None
        if k in CREST_FILE:
            info = file_info(CREST_FILE[k])
            if info and OK_LICENCE.match(info["licence"]):
                found = (CREST_FILE[k], info)
        for api, title in () if found else (("https://en.wikipedia.org/w/api.php", EN_TITLES.get(k, f"{c['en']} clan")),
                           ("https://ja.wikipedia.org/w/api.php", JA_TITLES.get(k, c["ja"] + "氏"))):
            name = lead_image(api, title)
            if name and name.lower().endswith(".svg"):
                info = file_info(name)
                if info and OK_LICENCE.match(info["licence"]):
                    found = (name, info)
                    break
                skipped.append((k, name, info and info["licence"] or "not on Commons"))
        if not found:
            skipped.append((k, "-", "no SVG crest found"))
            continue
        name, info = found
        orig = info["original"]  # the file's direct address: the Special:FilePath redirect is throttled harder
        path = os.path.join(OUT, k + ".svg")
        svg = None
        for attempt in range(4):
            time.sleep(6)  # one request every few seconds stays under Wikimedia's limit
            try:
                with urllib.request.urlopen(urllib.request.Request(orig, headers=w.UA), timeout=60) as r:
                    svg = r.read()
                break
            except Exception as e:
                err = e
                time.sleep(30)
        if svg is None:
            skipped.append((k, name, f"download failed: {err}"))
            continue
        if len(svg) > 120_000:
            skipped.append((k, name, f"too detailed ({len(svg) // 1024} KB)"))
            continue
        open(path, "wb").write(svg)
        result[k] = {"src": f"crests/{k}.svg", "file": name, "page": info["page"], "licence": info["licence"], "artist": info["artist"]}
        print("ok  ", k, "<-", name, "|", info["licence"], flush=True)
    with open(path_js, "w", encoding="utf8") as f:
        f.write("// Generated by tools/fetch_crests.py: each clan's family crest (kamon), from Wikimedia Commons.\n")
        f.write("const CRESTS = " + json.dumps(result, ensure_ascii=False, indent=1) + ";\n")
    print("\nkept", len(result))
    for s in skipped:
        print("skip", *s)


if __name__ == "__main__":
    main()
