def terms(a, b):
    return np.stack([np.ones_like(a), a, b, a * b, a * a, b * b], axis=1)


def main():
    js = open(os.path.join(ROOT, "data", "provinces.js"), encoding="utf8").read()
    geo = json.loads(js[js.index("{"):js.rindex("}") + 1])["provinces"]
    ids = sorted(CENTRES)
    lat = np.array([CENTRES[i][0] for i in ids]); lon = np.array([CENTRES[i][1] for i in ids])
    x = np.array([geo[i]["cx"] for i in ids]); y = np.array([geo[i]["cy"] for i in ids])
    fwd = [np.linalg.lstsq(terms(lon, lat), v, rcond=None)[0] for v in (x, y)]   # (lon, lat) -> map
    inv = [np.linalg.lstsq(terms(x, y), v, rcond=None)[0] for v in (lon, lat)]   # map -> (lon, lat)
    px, py = terms(lon, lat) @ fwd[0], terms(lon, lat) @ fwd[1]
    err = np.hypot(px - x, py - y)
    print(f"fit error in map units: median {np.median(err):.1f}, max {err.max():.1f} ({ids[err.argmax()]}); the map is about 760 wide")
    with open(os.path.join(ROOT, "data", "georef.js"), "w", encoding="utf8") as f:
        f.write("// Generated by tools/georef.py: map position <-> longitude/latitude, fitted on the provinces' centres.\n")
        f.write("// terms: 1, a, b, a*b, a*a, b*b. TO_MAP takes (lon, lat); TO_LONLAT takes (x, y).\n")
        f.write("const GEOREF = " + json.dumps({"toMap": [list(map(float, c)) for c in fwd], "toLonLat": [list(map(float, c)) for c in inv]}) + ";\n")
    return fwd, inv


if __name__ == "__main__":
    main()
