"""Downloads one picture per event and per clan from Wikipedia's articles, with its licence and author, into
images/ and data/images.js. Only public domain and Creative Commons files from Wikimedia Commons are kept; anything
else (fair-use uploads, unclear licences) is skipped. Run: python tools/fetch_images.py"""
import json, os, re, sys, time, urllib.parse, urllib.request

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import wiki_check as w

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "images")
OK_LICENCE = re.compile(r"^(public domain|pd|cc0|cc[- ]by(-sa)?[- ][\d.]+)", re.I)
# a better picture than the article's lead image, where Wikipedia's lead is a map or a modern photo
PREFER = {}


def page_images(titles):
    """{title: Commons file name} for the articles' lead images."""
    out = {}
    for i in range(0, len(titles), 20):
        d = w.get({"action": "query", "prop": "pageimages", "piprop": "name", "redirects": 1, "titles": "|".join(titles[i:i + 20])})["query"]
        alias = {n["from"]: n["to"] for n in d.get("normalized", []) + d.get("redirects", [])}
        names = {p["title"]: p.get("pageimage") for p in d["pages"]}
        for t in titles[i:i + 20]:
            r = alias.get(alias.get(t, t), alias.get(t, t))
            if names.get(r):
                out[t] = names[r]
    return out


def file_info(name):
    url = "https://commons.wikimedia.org/w/api.php?" + urllib.parse.urlencode({
        "action": "query", "format": "json", "formatversion": 2, "titles": "File:" + name, "prop": "imageinfo",
        "iiprop": "url|extmetadata|size", "iiurlwidth": 640})
    for attempt in range(5):
        time.sleep(1.5)
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=w.UA), timeout=30) as r:
                pages = json.load(r)["query"]["pages"]
            break
        except Exception:
            time.sleep(15 * (attempt + 1))
    else:
        return None
    if not pages or "imageinfo" not in pages[0]:
        return None  # not on Commons (a local fair-use upload)
    ii = pages[0]["imageinfo"][0]
    meta = {k: re.sub(r"<[^>]+>", "", str(v.get("value", ""))).strip() for k, v in ii.get("extmetadata", {}).items()}
    return {"thumb": ii.get("thumburl") or ii["url"], "page": ii["descriptionurl"], "licence": meta.get("LicenseShortName", ""),
            "artist": re.sub(r"\s+", " ", meta.get("Artist", "Unknown"))[:120], "desc": re.sub(r"\s+", " ", meta.get("ImageDescription", ""))[:200],
            "w": ii.get("thumbwidth"), "h": ii.get("thumbheight")}


def download(url, path):
    for attempt in range(5):
        time.sleep(1.5)
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=w.UA), timeout=60) as r, open(path, "wb") as f:
                f.write(r.read())
            return True
        except Exception:
            time.sleep(15 * (attempt + 1))
    return False


def main():
    h = w.load_history()
    wanted = {}  # key ("event:id" / "clan:id") -> article title
    for e in h["EVENTS"]:
        wanted["event:" + e["id"]] = w.EVENT_TITLES.get(e["id"], e["en"])
    for k, c in h["CLANS"].items():
        if c["people"]:
            wanted["clan:" + k] = c["people"][0][0].split(" (")[0]  # the clan's first key person: usually a portrait
    titles = sorted(set(wanted.values()))
    files = page_images(titles)
    os.makedirs(OUT, exist_ok=True)
    result, skipped = {}, []
    for key, title in wanted.items():
        name = PREFER.get(key) or files.get(title)
        if not name or name.lower().endswith((".svg", ".gif")):
            skipped.append((key, title, name or "no image"))
            continue
        info = file_info(name)
        if not info or not OK_LICENCE.match(info["licence"]):
            skipped.append((key, title, f"{name}: {info and info['licence'] or 'not on Commons'}"))
            continue
        local = re.sub(r"[^\w.-]+", "_", key) + os.path.splitext(name)[1].lower().replace(".jpeg", ".jpg")
        if not download(info["thumb"], os.path.join(OUT, local)):
            skipped.append((key, title, "download failed"))
            continue
        result[key] = {"src": "images/" + local, "file": name, "page": info["page"], "licence": info["licence"],
                       "artist": info["artist"], "w": info["w"], "h": info["h"], "desc": info["desc"]}
        print("ok  ", key, "<-", name, "|", info["licence"])
    with open(os.path.join(ROOT, "data", "images.js"), "w", encoding="utf8") as f:
        f.write("// Generated by tools/fetch_images.py: one picture per event and clan, from Wikimedia Commons.\n")
        f.write("const IMAGES = " + json.dumps(result, ensure_ascii=False, indent=1) + ";\n")
    print("\nkept", len(result), "skipped", len(skipped))
    for s in skipped:
        print("skip", *s)


if __name__ == "__main__":
    main()
